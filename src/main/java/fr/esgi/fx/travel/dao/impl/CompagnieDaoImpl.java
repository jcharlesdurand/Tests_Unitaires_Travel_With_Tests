package fr.esgi.fx.travel.dao.impl;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

import fr.esgi.fx.travel.business.Compagnie;
import fr.esgi.fx.travel.dao.CompagnieDao;
import fr.esgi.fx.travel.dao.ConnexionBdd;
import fr.esgi.fx.travel.dao.Requetes;

/**
 * Cette classe fait partie de la couche d'accès aux données (DAL
 * pour Data Acces Layer)
 *
 * DAO : Data Access Object
 *
 * Aujourd'hui on utilise souvent le terme de Repository
 * au lieu du terme DAO
 *
 * Repository fonctionne ac une base SQL mais également avec une base
 * NoSQL (Cassandra, MongoDB)
 *
 * Les classes de cette couche contiennent des méthodes CRUD
 * C : Create
 * R : Read (ou Retrieve)
 * U : Update
 * D : Delete
 *
 * Dans cette classe il n'y a pas de méthode de mise à jour
 * (pas de U), par conséquent cette classe est un CRD
 *
 * Dans le cahier des charges, la mise à jour d'une compagnie n'était
 * pas demandée.
 * Ne perdons pas de temps à écrire la méthode U si elle n'est pas
 * demandée
 * YAGNI : You Aren't Gonna Need It
 */
public class CompagnieDaoImpl implements CompagnieDao {

	// Attribut qui établit une connexion avec la bdd
	private Connection connexion;

	public CompagnieDaoImpl() {
		try {
			connexion = ConnexionBdd.getConnection();
		} catch (ClassNotFoundException e) {
			// TODO Auto-generated catch block
			e.printStackTrace();
		} catch (SQLException e) {
			// TODO Auto-generated catch block
			e.printStackTrace();
		}
	}

	/**
	 * Cette méthode ajoute en base (dans la table compagnie) la compagnie donnée en
	 * paramètre
	 * 
	 * @param un objet de type compagnie dont l'id est null
	 * @return l'objet compagnie ayant un id non null ayant été choisi par la bdd
	 */
	@Override
	public Compagnie create(Compagnie compagnie) throws SQLException {
		// Dans la classe java.sql.Connection, la méthode prepareStatement est
		// surchargée (il y a 6 méthodes prepareStatement)
		// on invoque celle avec deux paramètres : le premier de type String
		// correspondant à la requête SQL à exécuter
		// le deuxième de type int : extrait de la Javadoc : autoGeneratedKeys - a flag
		// indicating whether auto-generated keys should be returned; one of
		// Statement.RETURN_GENERATED_KEYS or Statement.NO_GENERATED_KEYS
		PreparedStatement preparedStatement = connexion.prepareStatement(Requetes.AJOUT_COMPAGNIE,
				Statement.RETURN_GENERATED_KEYS);
		// On remplace le premier point d'interrogation par le nom de la compagnie
		// donnée en paramètre
		preparedStatement.setString(1, compagnie.getNom());
		// On demande l'excution de la requête INSERT
		preparedStatement.executeUpdate();
		// On invoque la méthode getGeneratedKeys(), ce qui est légitime de par
		// l'utilisation de Statement.RETURN_GENERATED_KEYS
		// cette méthode renvoie un objet de type ResultSet
		ResultSet resultSet = preparedStatement.getGeneratedKeys();
		// On teste si le resulSet contient des données
		if (resultSet.next()) {
			// On affecte à la compagnie donnée en paramètre l'id choisi par la bdd
			compagnie.setId(resultSet.getLong(1));
		}
		return compagnie;
	}

	@Override
	public Compagnie findOne(Long id) throws SQLException {
		// On prépare une requête SQL qui va transiter sur la connexion liée à
		// l'application
		PreparedStatement ps = connexion.prepareStatement(Requetes.COMPAGNIE_PAR_ID);
		// On transforme le premier ? par l'id donné en paramètre
		ps.setLong(1, id);
		// On demande à MySQL d'exécuter la requête
		// et JDBC va placer les résultats dans l'objet ResultSet
		ResultSet rs = ps.executeQuery();

		// Si l'objet ResultSet contient des données..
		if (rs.next()) {
			// On charge ces données dans un nouvel objet de type Compagnie
			Compagnie compagnie = new Compagnie();
			// la donnée lue dans la colonne nom est affectée au nom
			// de l'objet compagnie
			compagnie.setNom(rs.getString("nom"));
			// la donnée lue dans la colonne id est affectée au nom
			// de l'objet compagnie
			compagnie.setId(rs.getLong("id"));
			return compagnie;
		}
		return null;
	}

	@Override
	public List<Compagnie> findAll() throws SQLException {
		List<Compagnie> compagnies = new ArrayList<>();
		PreparedStatement ps = connexion.prepareStatement(Requetes.TOUTES_LES_COMPAGNIES);
		ResultSet rs = ps.executeQuery();
		while (rs.next()) {
			Compagnie compagnie = new Compagnie(rs.getString("nom"));
			compagnie.setId(rs.getLong("id"));
			compagnies.add(compagnie);
		}
		return compagnies;
	}

	@Override
	public boolean delete(Long id) throws SQLException {
		if (findOne(id) == null) {
			return false;
		}
		PreparedStatement ps = connexion.prepareStatement(Requetes.SUPPRESSION_COMPAGNIE);
		ps.setLong(1, id);
		ps.executeUpdate();
		return true;
	}

}
