alter table if exists vol drop constraint FK3;
drop table if exists vol;
drop table if exists compagnie;
drop table if exists aeroport;
create table aeroport (id bigint generated by default as identity, nom varchar(255), primary key (id));
create table compagnie (id bigint generated by default as identity, nom varchar(255), primary key (id));
create table vol (id bigint generated by default as identity, heure_arrivee time, heure_depart time, prix_en_euros float not null, aeroport_arrivee_id bigint, aeroport_depart_id bigint, compagnie_id bigint, primary key (id));
alter table vol add constraint FK1 foreign key (aeroport_arrivee_id) references aeroport;
alter table vol add constraint FK2 foreign key (aeroport_depart_id) references aeroport;
alter table vol add constraint FK3 foreign key (compagnie_id) references compagnie;